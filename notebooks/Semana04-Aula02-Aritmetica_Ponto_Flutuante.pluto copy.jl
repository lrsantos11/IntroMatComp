# Implementação
function raizes_big(a,b,c)
	a, b, c = BigFloat(a), BigFloat(b), BigFloat(c)
	r₁, r₂ = raizes(a,b,c) 
	return float(r₁), float(r₂) # Float32
end

# ╔═╡ ca8effda-244a-4da8-b2c5-3f2ff7b321d7
raizes_big(1,2,-1)

